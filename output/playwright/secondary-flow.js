async (page) => {
  const results=[];
  await page.getByRole('link',{name:'模型与行动',exact:true}).click();
  await page.getByRole('button',{name:'添加模型',exact:true}).click();
  const type='QA'+Date.now();
  await page.locator('#model-name').fill('新增演示模型');
  await page.locator('#model-type').fill(type);
  await page.locator('#model-code').fill('CODE_'+type);
  await page.locator('#model-form').getByRole('button').count();
  await page.locator('.modal-footer').getByRole('button',{name:'添加模型',exact:true}).click();
  await page.getByRole('dialog').waitFor({state:'hidden'});
  await page.getByRole('heading',{name:'新增演示模型',exact:true}).waitFor();
  results.push('model creation');
  await page.getByRole('link',{name:'设置',exact:true}).click();
  await page.getByRole('textbox',{name:'想定输入目录',exact:true}).fill('./demo/scenarios');
  await page.getByRole('button',{name:'保存设置',exact:true}).click();
  await page.getByText('设置已保存到当前浏览器。',{exact:true}).waitFor();
  await page.reload();
  if(await page.getByRole('textbox',{name:'想定输入目录',exact:true}).inputValue()!=='./demo/scenarios')throw Error('Settings did not persist');
  results.push('settings persistence');
  await page.getByRole('link',{name:'方案管理',exact:true}).click();
  const all=page.getByRole('checkbox',{name:'选择全部可见方案',exact:true});
  await all.check();if(!await all.isChecked())throw Error('Select all state was lost');
  await all.uncheck();if(await page.locator('[data-select]:checked').count())throw Error('Deselect failed');
  results.push('select all / deselect');
  await page.getByRole('checkbox',{name:'选择 多实体协同行动',exact:true}).check();
  await page.getByRole('checkbox',{name:'选择 挂载数量边界验证',exact:true}).check();
  await page.getByRole('button',{name:'批量运行 · 2',exact:true}).click();
  await page.getByRole('button',{name:'提交可运行的 1 项',exact:true}).waitFor();
  if(!(await page.getByRole('dialog').innerText()).includes('跳过'))throw Error('Invalid batch item not identified');
  await page.locator('#mock-outcome').selectOption('missing');
  await page.getByRole('button',{name:'提交可运行的 1 项',exact:true}).click();
  await page.getByText('模拟执行已结束，可逐条查看行动结论与证据。',{exact:true}).waitFor({timeout:20000});
  await page.getByRole('button',{name:'行动判读 · 2',exact:true}).click();
  if(!(await page.locator('.detail-content').innerText()).includes('未发现'))throw Error('Missing event verdict failed');
  results.push('partial-valid batch / missing event');
  await page.getByRole('button',{name:'重新运行',exact:true}).click();
  await page.getByRole('button',{name:'提交可运行的 1 项',exact:true}).click();
  await page.getByRole('button',{name:'取消执行',exact:true}).click();
  await page.getByText('已取消',{exact:true}).waitFor();
  results.push('cancel');
  await page.getByRole('link',{name:'方案管理',exact:true}).click();
  await page.getByRole('button',{name:'编辑 基础行动验证',exact:true}).click();
  await page.getByRole('textbox',{name:'实体名称',exact:true}).fill('导航保护回归测试');
  await page.getByRole('textbox',{name:'实体名称',exact:true}).press('Tab');
  await page.getByRole('link',{name:'SimTest. 仿真测试工作台',exact:true}).click();
  await page.getByRole('heading',{name:'保存当前修改',exact:true}).waitFor();
  await page.getByRole('button',{name:'放弃修改',exact:true}).click();
  await page.getByRole('heading',{name:'方案管理',exact:true}).waitFor();
  results.push('unsaved navigation guard');
  await page.setViewportSize({width:390,height:844});
  await page.screenshot({path:'output/playwright/mobile.png',fullPage:true});
  const overflow=await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth+1);
  if(overflow)throw Error('Mobile page has horizontal overflow');
  results.push('mobile layout');
  await page.setViewportSize({width:1440,height:1000});
  await page.evaluate(r=>window.qaResults=r,results);
}

async (page) => {
  const errors=[];page.on('pageerror',e=>errors.push(e.message));
  page.on('dialog',dialog=>dialog.accept());
  await page.goto('http://127.0.0.1:4173/#/plans');
  await page.evaluate(()=>localStorage.removeItem('simtest-demo-v1'));
  await page.reload();
  await page.setViewportSize({width:1440,height:1000});
  await page.screenshot({path:'output/playwright/dashboard.png'});
  await page.getByRole('button',{name:'编辑 基础行动验证',exact:true}).click();
  await page.locator('#scenario-map svg').waitFor();
  await page.screenshot({path:'output/playwright/map.png'});
  await page.getByRole('button',{name:'添加实体',exact:true}).click();
  await page.locator('#create-count').fill('1');
  await page.getByRole('button',{name:'开始批量布置',exact:true}).click();
  const mapBox=await page.locator('#scenario-map .map-svg-wrap').boundingBox();
  await page.locator('#scenario-map .map-svg-wrap').click({position:{x:mapBox.width*.14,y:mapBox.height*.17}});
  if(await page.locator('.entity-item').count()!==3)throw Error('Map placement did not add an entity');
  await page.getByText('实例信息',{exact:true}).click();
  if(!(await page.locator('.entity-props').innerText()).includes('资源编号'))throw Error('Ordinary entity must use its resource number');
  await page.getByRole('button',{name:'添加挂载',exact:true}).click();
  await page.locator('#create-count').fill('4');
  await page.locator('#create-category-0').selectOption('物资');
  await page.locator('#create-category-2').selectOption('导弹');
  if(await page.locator('#create-model option:checked').innerText()!=='某型弹药')throw Error('Weapon entity model was not selected by classification');
  await page.getByRole('button',{name:'添加挂载实体',exact:true}).click();
  await page.getByRole('button',{name:'行动指令 1',exact:true}).click();
  await page.getByRole('button',{name:'添加行动',exact:true}).click();
  await page.locator('[name=executors]').first().uncheck();
  await page.locator('[name=executors]').nth(1).check();
  await page.locator('#action-target').selectOption({index:1});
  await page.locator('#action-weapon').check();
  await page.locator('#action-count').fill('5');
  await page.getByRole('button',{name:'保存行动',exact:true}).click();
  if(!(await page.getByRole('alert').innerText()).includes('超出'))throw Error('Over-allocation was not blocked');
  await page.locator('#action-count').fill('2');
  await page.getByRole('button',{name:'保存行动',exact:true}).click();
  await page.getByRole('dialog').waitFor({state:'hidden'});
  if(await page.locator('.editor-body tbody tr').count()!==2)throw Error('Action save failed');
  await page.getByRole('button',{name:'生成文件',exact:true}).click();
  await page.getByRole('button',{name:'导出配套 ZIP',exact:true}).waitFor({state:'visible'});
  const downloadPromise=page.waitForEvent('download');
  await page.getByRole('button',{name:'导出配套 ZIP',exact:true}).click();
  const downloaded=await downloadPromise;await downloaded.saveAs('output/playwright/exported-inputs.zip');
  await page.screenshot({path:'output/playwright/generated-files.png'});
  await page.getByRole('button',{name:'模拟运行',exact:true}).click();
  await page.locator('#mock-outcome').selectOption('success');
  await page.getByRole('button',{name:'提交可运行的 1 项',exact:true}).click();
  await page.getByText('模拟执行已结束，可逐条查看行动结论与证据。',{exact:true}).waitFor({timeout:20000});
  await page.getByRole('button',{name:'行动判读 · 2',exact:true}).click();
  await page.getByRole('button',{name:'查看',exact:true}).first().click();
  await page.screenshot({path:'output/playwright/results.png'});
  if(!(await page.locator('.evidence-row').innerText()).includes('success'))throw Error('Missing simulated evidence');
  await page.getByRole('button',{name:'人工备注',exact:true}).click();
  await page.locator('#review-verdict').selectOption('pass');
  await page.locator('#review-note').fill('前端交互验收：模拟证据展示正确。');
  await page.getByRole('button',{name:'保存备注',exact:true}).click();
  await page.getByRole('dialog').waitFor({state:'hidden'});
  await page.getByRole('button',{name:'演示复盘',exact:true}).click();
  await page.locator('#replay-map svg').waitFor();
  await page.locator('#replay-slider').fill('50');
  if(!(await page.locator('#replay-time').innerText()).includes('6300'))throw Error('Replay seek failed');
  await page.getByRole('button',{name:'关闭',exact:true}).click();
  await page.reload();
  await page.getByRole('heading',{name:'基础行动验证',exact:true}).waitFor();
  if(!(await page.locator('.detail-content').innerText()).includes('前端交互验收'))throw Error('Review did not persist');
  if(errors.length)throw Error('Browser errors: '+errors.join('; '));
  console.log('PASS: map and mounted-entity creation, resource IDs, inventory guard, action editing, paired ZIP export, mock run, evidence, review, replay and persistence.');
}
